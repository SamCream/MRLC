const assert=require('node:assert/strict');
const path=require('node:path');
const base=process.argv[2];
const {LocalSystemRepository}=require(path.join(base,'data/systemRepository.js'));
const {LocalSettingsRepository,runtimeDefaults,appearanceDefaults}=require(path.join(base,'data/settingsRepository.js'));
const {getLocalProjectOverview,projectOverview}=require(path.join(base,'data/overviewRepository.js'));
const {localWorkspaceRepository:workspace}=require(path.join(base,'data/workspaceRepository.js'));
const {localOrganizationRepository:org}=require(path.join(base,'data/organizationRepository.js'));
const {localComputeRepository:compute}=require(path.join(base,'data/computeRepository.js'));

(async()=>{
  const settings=new LocalSettingsRepository(org);
  const one=await settings.getRuntimeSettings('project-1');
  assert.equal(one.contextPolicy,'task');assert.equal(one.revision,1);
  const second=await settings.updateRuntimeSettings('project-1',{...runtimeDefaults,modelId:'my-local/32b',contextPolicy:'project'},1);
  assert.equal(second.revision,2);assert.equal(second.modelId,'my-local/32b');
  assert.equal((await settings.getRuntimeSettings('project-2')).modelId,runtimeDefaults.modelId,'per-project isolation');
  await assert.rejects(()=>settings.updateRuntimeSettings('project-1',runtimeDefaults,1),/revision conflict/);
  await assert.rejects(()=>settings.updateRuntimeSettings('project-1',{...runtimeDefaults,modelId:''},2),/Model ID/);
  await assert.rejects(()=>settings.getRuntimeSettings('missing-project'),/Project not found/);
  const reverted=await settings.resetRuntimeSettings('project-1',2);
  assert.equal(reverted.revision,3);assert.equal(reverted.modelId,runtimeDefaults.modelId);
  const app=await settings.saveAppearance({...appearanceDefaults,theme:'soft-dark'});
  assert.equal(app.theme,'soft-dark');assert.equal((await settings.getAppearance()).theme,'soft-dark');
  assert.equal(JSON.parse(localStorage.getItem('mrlc.settings.demo.v5')).appearance.theme,'soft-dark');
  await assert.rejects(()=>settings.saveAppearance({...appearanceDefaults,theme:'nonsense'}),/Invalid appearance/);
  await settings.resetAppearance();assert.equal((await settings.getAppearance()).theme,'strata-dark');
  const system=new LocalSystemRepository(workspace);
  assert.equal(await system.getHealth(),null);assert.equal(await system.runHealthCheck(),null);
  assert.equal(await system.getTopology(),null);assert.deepEqual((await system.listNodes()).items,[]);
  assert.deepEqual((await system.listAccelerators()).items,[]);
  const logs=(await system.listLogs({projectId:'project-1'})).items;
  assert.equal(logs.length,2);assert.equal(logs.every(x=>x.projectId==='project-1'),true);
  assert.equal((await system.listLogs({projectId:'project-2'})).items.length,0);
  assert.equal((await system.listLogs({projectId:'project-1',level:'error'})).items.length,0);
  assert.equal((await system.listLogs({projectId:'project-1',q:'proof'})).items.length,1);
  assert.equal((await system.listLogs({projectId:'project-1',source:'Reviewer'})).items.length,1);
  const first=await system.listLogs({projectId:'project-1',limit:1});assert.equal(first.items.length,1);assert.equal(first.nextCursor,'1');
  const next=await system.listLogs({projectId:'project-1',limit:1,cursor:first.nextCursor});assert.equal(next.items.length,1);assert.equal(next.nextCursor,null);
  assert.notEqual(first.items[0].id,next.items[0].id);
  await assert.rejects(()=>system.listLogs({cursor:'NaN'}),/Invalid cursor/);
  const saved=await system.saveLogView('My incidents',{projectId:'project-1',level:'error'});
  assert.equal((await system.listLogViews()).items[0].filter.level,'error');
  await system.deleteLogView(saved.id);assert.equal((await system.listLogViews()).items.length,0);
  const overview=await getLocalProjectOverview('project-1');
  assert.equal(overview.taskCount,6);assert.equal(overview.agents.length,4);
  assert.equal(overview.pendingApprovals,2);assert.equal(overview.activeSlots,2);assert.equal(overview.totalSlots,2);
  assert.equal(overview.queuedTasks,3);assert.equal(overview.progressPercent,Math.round((80+0+0+80+60+0)/6));
  assert.equal(overview.stages.length,1);assert.equal(overview.stages[0].level,'high');
  assert.equal(overview.health,null);assert.equal(overview.metrics,null);assert.equal(overview.budget,null);
  const isolated=await getLocalProjectOverview('project-2');
  assert.equal(isolated.taskCount,0);assert.equal(isolated.activeSlots,0);
  assert.equal(isolated.stages.length,0);assert.equal(isolated.pendingApprovals,1);
  const synthetic=projectOverview('project-1',{tasks:overview.tasks,agents:overview.agents,approvals:overview.approvals,artifacts:overview.artifacts,queue:overview.queue,slots:(await compute.listSlots()).items,channels:[],messages:[]});
  assert.equal(synthetic.stages.length,0);
  const archive=await org.createProject({name:'Settings archive guard',description:''});
  await org.archiveProject(archive.id);
  await assert.rejects(()=>settings.updateRuntimeSettings(archive.id,runtimeDefaults,1),/Archived projects/);
  assert.equal(JSON.parse(localStorage.getItem('mrlc.settings.demo.v5')).runtime['project-1'].revision,3);
  console.log('PASS: Phase 5 repositories / project isolation / CAS / real-source logs / honest health / overview derived metrics / appearance');
})().catch(e=>{console.error(e);process.exitCode=1;});
